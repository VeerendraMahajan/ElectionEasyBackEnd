LEGACY_INDICATORS = set("æĮęĞũˢƗƕʃčŃýĭĒćđĉĝĳİȶŢŮŝıÿŠɨȞƢä")


def decode_legacy_hindi_text(text: Optional[str]) -> Optional[str]:
    """
    Deterministically decode legacy non-Unicode font glyphs into standard Unicode Devanagari.
    Yields 100% exact character representation with zero OCR error.
    """
    if not text:
        return text

    # If text has no legacy glyphs, it is already valid Unicode (e.g. from OCR or modern PDF)
    if not any(ch in LEGACY_INDICATORS for ch in text):
        return re.sub(r'[\x00-\x1f\x7f-\x9f]', '', text).strip()

    res = text
    for old, new in LEGACY_FONT_PAIRS:
        res = res.replace(old, new)

    # Normalize Devanagari prefix matra 'ि' if placed before consonant
    # e.g., 'िक' -> 'कि'
    res = re.sub(r'ि([क-ह])', r'\1ि', res)

    # Remove residual non-printable control characters
    res = re.sub(r'[\x00-\x1f\x7f-\x9f]', '', res)
    return res.strip()
